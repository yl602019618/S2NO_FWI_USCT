def make_parameters():
    """Return the original geometry, grid units and 50 mm pair mask."""
    x = np.array(X_1BASED, dtype=np.int64)
    y = np.array(Y_1BASED, dtype=np.int64)
    linear = x + (y - 1) * 480
    distance = np.sqrt((x[:, None] - x[None, :]) ** 2
                       + (y[:, None] - y[None, :]) ** 2) * 50
    select = (distance >= 5000).astype(float)
    return {
        "NX": 480, "NY": 480, "nx": 480, "ny": 480,
        "dh": 50.0, "npml": 0, "l": 2, "NYX": 480 * 480,
        "mute_dist": 5000, "x_rec": x, "y_rec": y, "n_rec": 256,
        "i_rec": linear, "x_src": x.copy(), "y_src": y.copy(),
        "n_src": 256, "i_src": linear.copy(), "select_mat": select, "freq": 5.0,
    }


def circular_roi(center, radius):
    """The original strict-inside disk in 0-based array coordinates."""
    row, col = np.indices((480, 480))
    return (np.sqrt((row - center[0]) ** 2 + (col - center[1]) ** 2) < radius).astype(int)
